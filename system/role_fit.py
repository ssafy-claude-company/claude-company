def tokens(text):
    return [t.lower() for t in _TOKEN.findall(text or "")]


def _hints_for(role):
    """직군명에 맞는 힌트 집합 — 키 정확일치 + 정규화 부분포함('게임 기획자'→'게임기획' 힌트)."""
    # [한방향 — 특화만 상속(2026-07-14)] 직군명이 힌트 키를 *포함*할 때만 그 힌트를 받는다
    # ('게임 기획자'⊃'게임기획' → 게임 힌트 O). 반대(일반 '기획'이 '게임기획'에 포함돼 게임 힌트를
    # 주워가는 것)는 막는다 — 일반직이 전문 힌트를 상속하면 적합 비교가 무너진다.
    rn = "".join(str(role or "").lower().split())
    out = set()
    for key, hs in ROLE_HINTS.items():
        kn = "".join(key.lower().split())
        if kn and (kn == rn or kn in rn):
            out.update(hs)
    return out


def _overlap(qs, ts):
    """[합성어 매칭(2026-07-20, U-035 실측)] 정확 일치만 보면 한국어 합성어를 놓친다 —
    '웹게임' 과제에 '게임 기획자'가 0점(웹게임≠게임). 2글자 이상 토큰의 부분포함을 겹침으로
    인정(한방향 아님 — 양방향 포함, 보수적 길이 가드)."""
    n = 0
    for t in ts:
        if any(t == q or (len(t) >= 2 and t in q) or (len(q) >= 2 and q in t) for q in qs):
            n += 1
    return n


def role_fit(query, role):
    """직군이 과제(query)에 얼마나 맞나 — 정수 점수. 직군명 직접 겹침 ×2 + 의미 힌트 겹침 ×1.
    직군명 하드 매칭이 아니라 시소러스 기반이라, 같은 계열(기획 vs 게임 기획자)에서 과제 도메인의
    전문가가 더 높게 나온다. 후보 비교용(절대값 의미 없음, 상대 순위만)."""
    q = set(tokens(query))
    return _overlap(q, set(tokens(role))) * 2 + _overlap(q, _hints_for(role))
