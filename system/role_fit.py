"""[역할-과제 적합성 — 단일 진실원(2026-07-14)] 직군이 과제에 얼마나 맞는지의 순수 점수.

원래 murmur/backend/sns/recommend.py(F1301 추천)에만 있던 역할 적합 로직을 브레인(system/)으로
끌어올린다 — 이유: ①선거(_elect_proposer의 유사직군 대표 선택)도 같은 '역할 적합'을 봐야 하는데,
매체중립 원칙상 system/이 murmur/backend를 import할 수 없다. ②적합성은 매체가 아니라 도메인 개념이다.
그래서 여기(브레인)가 정본이 되고, 추천(웹)은 이걸 재사용한다(반대 방향 의존은 허용).

핵심 신호 = 질의(과제 원문) 토큰 ∩ [직군명 토큰 ×2(직접) + 직군 힌트(의미 시소러스)].
'게임 기획자'는 힌트 '게임·레벨·밸런스…'로 게임 과제에 강하게 붙고, 일반 '기획'은 안 붙는다 —
하드 문자열 포함이 아니라 의미 기반이라 '게임엔 게임 기획자'가 자연히 나온다.
"""
import re

_TOKEN = re.compile(r"[0-9A-Za-z가-힣]+")

# 도메인 키워드 → 직군 시소러스. 질의가 직군명을 직접 안 써도(예: '실시간 멀티플레이 서버') 해당
# 직군으로 매칭. 키는 정규화(공백 제거) 후 직군명에 부분포함으로도 매칭한다('게임 기획자'⊃'게임기획').
ROLE_HINTS = {
    "백엔드":      ["서버", "api", "db", "데이터베이스", "backend", "로직", "인증", "배포", "실시간", "소켓", "동기화"],
    "프론트엔드":  ["프론트", "ui", "ux", "화면", "frontend", "리액트", "react", "뷰", "vue", "css", "웹", "렌더", "반응형"],
    "기획":        ["기획", "planner", "요구사항", "스펙", "와이어프레임", "유저스토리", "정책"],
    "게임기획":    ["게임", "레벨", "밸런스", "game", "플레이", "재미", "스테이지", "메커닉", "협동", "룰"],
    "QA":          ["qa", "테스트", "품질", "버그", "검증", "엣지", "test", "회귀", "안정성"],
    "디자인":      ["디자인", "design", "컬러", "아트", "비주얼", "스타일"],
    "PM":          ["pm", "일정", "관리", "리더", "총괄", "조율", "로드맵"],
}


def tokens(text):
    return [t.lower() for t in _TOKEN.findall(text or "")]


def _hints_for(role):
    """직군명에 맞는 힌트 집합 — 키 정확일치 + 정규화 부분포함('게임 기획자'→'게임기획' 힌트)."""
    # [한방향 — 특화만 상속(2026-07-14)] 직군명이 힌트 키를 *포함*할 때만 그 힌트를 받는다
    # ('게임 기획자'⊃'게임기획' → 게임 힌트 O). 반대(일반 '기획'이 '게임기획'에 포함돼 게임 힌트를
    # 주워가는 것)는 막는다 — 일반직이 전문 힌트를 상속하면 적합 비교가 무너진다.
    rn = "".join(str(role or "").lower().split())
    out = set()
    for key, hs in ROLE_HINTS.items():
        kn = "".join(key.lower().split())
        if kn and (kn == rn or kn in rn):
            out.update(hs)
    return out


def _overlap(qs, ts):
    """[합성어 매칭(2026-07-20, U-035 실측)] 정확 일치만 보면 한국어 합성어를 놓친다 —
    '웹게임' 과제에 '게임 기획자'가 0점(웹게임≠게임). 2글자 이상 토큰의 부분포함을 겹침으로
    인정(한방향 아님 — 양방향 포함, 보수적 길이 가드)."""
    n = 0
    for t in ts:
        if any(t == q or (len(t) >= 2 and t in q) or (len(q) >= 2 and q in t) for q in qs):
            n += 1
    return n


def role_fit(query, role):
    """직군이 과제(query)에 얼마나 맞나 — 정수 점수. 직군명 직접 겹침 ×2 + 의미 힌트 겹침 ×1.
    직군명 하드 매칭이 아니라 시소러스 기반이라, 같은 계열(기획 vs 게임 기획자)에서 과제 도메인의
    전문가가 더 높게 나온다. 후보 비교용(절대값 의미 없음, 상대 순위만)."""
    q = set(tokens(query))
    return _overlap(q, set(tokens(role))) * 2 + _overlap(q, _hints_for(role))
